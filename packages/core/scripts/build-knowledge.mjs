import { readFile, readdir, writeFile } from "node:fs/promises";
import { format, resolveConfig } from "prettier";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
const root = new URL("../../../docs/research/", import.meta.url);
const official = (host) =>
  [
    "inps.it",
    "agenziaentrate.gov.it",
    "lavoro.gov.it",
    "interno.gov.it",
    "gazzettaufficiale.it",
    "normattiva.it",
    "garanteprivacy.it",
    "europa.eu",
    "agid.gov.it",
    "docs.italia.it",
    "spid.gov.it",
    "istat.it",
    "portaleimmigrazione.it",
  ].some((d) => host === d || host.endsWith("." + d));
const chunks = [];
for (const file of (await readdir(root))
  .filter((f) => f.endsWith(".md") && f !== "README.md")
  .sort()) {
  const md = await readFile(new URL(file, root), "utf8");
  const title = md.match(/^# (.+)/m)?.[1] ?? file;
  for (const section of md.split(/(?=^## )/m)) {
    const heading = section.match(/^## (.+)/m)?.[1] ?? title;
    const links = [...section.matchAll(/\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g)].map((m) => ({
      source: m[1],
      url: m[2],
    }));
    // Mixed vendor/institutional sections cannot be attributed wholly to an official source.
    if (!links.length || links.some((s) => !official(new URL(s.url).hostname))) continue;
    const sources = links;
    const text = section
      .replace(/^#{1,6} .+\n/gm, "")
      .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
      .replace(/\*\*/g, "")
      .trim();
    // Section IDs stay stable across edits; the corpus version changes with content.
    const sectionId = createHash("sha256")
      .update(file + "#" + heading)
      .digest("hex")
      .slice(0, 12);
    const paragraphs = text.split(/\n/);
    let parts = [],
      part = "";
    for (const paragraph of paragraphs) {
      if (part.length + paragraph.length > 2800 && part) {
        parts.push(part);
        part = "";
      }
      part += (part ? "\n\n" : "") + paragraph;
    }
    if (part) parts.push(part);
    parts.forEach((text, n) =>
      chunks.push({
        id: `kb:${sectionId}:${n}`,
        title: heading === title ? title : `${title} — ${heading}`,
        source: sources
          .map((s) => s.source)
          .join("; ")
          .slice(0, 500),
        url: sources[0].url,
        sources,
        file,
        practiceIds:
          file.startsWith("isee") || file === "dsu-prospetto.md"
            ? ["isee_ordinario", "isee_universitario"]
            : file === "modello-730.md"
              ? ["modello_730"]
              : file === "assegno-unico.md"
                ? ["assegno_unico"]
                : file === "permesso-soggiorno.md"
                  ? ["permesso_soggiorno"]
                  : [],
        text,
      }),
    );
  }
}
const version = createHash("sha256").update(JSON.stringify(chunks)).digest("hex").slice(0, 16);
await writeFile(
  new URL("../src/knowledge-data.ts", import.meta.url),
  await format(
    `// Generated by scripts/build-knowledge.mjs from sourced research sections.\nexport const KNOWLEDGE_VERSION = ${JSON.stringify(version)};\nexport const knowledgeChunks = ${JSON.stringify(chunks, null, 2)};\n`,
    {
      ...(await resolveConfig(fileURLToPath(new URL("../src/knowledge-data.ts", import.meta.url)))),
      parser: "typescript",
    },
  ),
);
console.log(JSON.stringify({ version, chunks: chunks.length }));
