export type TextKey = keyof typeof texts;
export function t(
  language: Language,
  key: TextKey,
  variables: Record<string, string | number> = {},
): string {
  const template = texts[key][languages.indexOf(language)] ?? texts[key][0];
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    String(variables[name] ?? `{${name}}`),
  );
}

export function localize(
  language: Language,
  text: Text,
  variables: Record<string, string | number> = {},
): string {
  return (text[languages.indexOf(language)] ?? text[0]).replace(/\{(\w+)\}/g, (_, name: string) =>
    String(variables[name] ?? `{${name}}`),
  );
}
